//! Начальная сцена: земля, солнце и камера.
//!
//! Пока это статичная картинка без связи с симуляцией. Она нужна, чтобы
//! проверить, что окно и рендер работают на всех системах. Карта появится
//! в вехе 4, управление камерой в вехе 3.
//!
//! Оси Bevy: X вправо, Y вверх, Z на зрителя. Единица длины это метр.
//! Объекты создаются обычным `commands.spawn`, без макроса `bsn!`
//! из примеров Bevy 0.20: так видно, из каких компонентов состоит объект.

use bevy::prelude::*;

/// Сторона квадратной плоскости земли в метрах. Подобрана под камеру:
/// верхний край кадра упирается в землю примерно в 35 м за центром сцены,
/// поэтому при стороне 50 м (25 м от центра) дальний край и фон за ним
/// попадают в кадр. При 100 м плоскость закрывала весь экран.
const GROUND_SIZE: f32 = 50.0;

/// Цвет земли: приглушённый зелёный, чтобы плоскость отличалась от фона.
const GROUND_COLOR: Color = Color::srgb(0.35, 0.45, 0.30);

/// Камера стоит на этой высоте над землёй (метры)...
const CAMERA_HEIGHT: f32 = 40.0;

/// ...и отодвинута от центра сцены на это расстояние по Z (метры).
/// 40 вверх и 28 назад дают угол примерно 55 градусов к земле,
/// привычный для RTS.
const CAMERA_BACK: f32 = 28.0;

/// Точка, из которой светит солнце. Направленный свет не имеет положения,
/// важно только направление от этой точки к центру сцены: солнце высоко,
/// справа и немного спереди.
const SUN_FROM: Vec3 = Vec3::new(30.0, 50.0, 20.0);

/// Создаёт землю, солнце и камеру. Выполняется один раз при запуске.
pub fn setup(
    mut commands: Commands,
    mut meshes: ResMut<Assets<Mesh>>,
    mut materials: ResMut<Assets<StandardMaterial>>,
) {
    // Земля: плоскость в плоскости XZ с центром в начале координат.
    let ground_mesh = Plane3d::default().mesh().size(GROUND_SIZE, GROUND_SIZE);
    commands.spawn((
        Mesh3d(meshes.add(ground_mesh)),
        MeshMaterial3d(materials.add(GROUND_COLOR)),
    ));

    // Солнце: параллельные лучи на всю сцену. Тени включены заранее,
    // хотя отбрасывать их пока нечему: первый куб появится в вехе 2.
    commands.spawn((
        DirectionalLight {
            shadow_maps_enabled: true,
            ..default()
        },
        Transform::from_translation(SUN_FROM).looking_at(Vec3::ZERO, Vec3::Y),
    ));

    // Камера смотрит в центр сцены сверху под углом.
    commands.spawn((
        Camera3d::default(),
        Transform::from_xyz(0.0, CAMERA_HEIGHT, CAMERA_BACK).looking_at(Vec3::ZERO, Vec3::Y),
    ));
}
