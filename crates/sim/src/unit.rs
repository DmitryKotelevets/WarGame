//! Юнит и его идентификатор.
//!
//! На юнит нельзя ссылаться обычной ссылкой Rust: юниты лежат в общем
//! хранилище, появляются и гибнут, а помнить друг о друге должны дольше
//! одного тика (цель атаки, выделение игрока, команда из реплея). Поэтому
//! везде хранится `UnitId`, а сам юнит по нему достаётся из `UnitStore`.
//!
//! В идентификаторе два числа. `index` это номер ячейки хранилища.
//! Ячейка погибшего юнита потом достаётся новому, поэтому одного номера
//! мало: старая ссылка «моя цель в ячейке 5» указала бы на чужой юнит.
//! `generation` (поколение) это счётчик того, сколько раз ячейку
//! освобождали. У нового жильца поколение другое, и старый идентификатор
//! перестаёт подходить.

use crate::vec2::Vec2Fixed;

/// Идентификатор юнита. Поля открыты: подделанный идентификатор безвреден
/// (хранилище просто никого по нему не найдёт), а хешу мира и реплею
/// нужны оба числа.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct UnitId {
    /// Номер ячейки в хранилище.
    pub index: u32,
    /// Сколько раз эту ячейку освобождали до появления этого юнита.
    pub generation: u32,
}

/// Юнит. Пока у него есть только место на карте: скорость и цель движения
/// появятся в шаге 2.8.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Unit {
    /// Собственный идентификатор. Повторяет номер ячейки, в которой юнит
    /// лежит, зато при обходе всех юнитов не нужно передавать его отдельно.
    pub id: UnitId,
    pub position: Vec2Fixed,
}
