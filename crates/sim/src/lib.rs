//! Детерминированное ядро игры.
//!
//! Здесь живёт вся игровая логика: мир, юниты, движение, бой, поиск пути.
//! Крейт ничего не знает о графике, времени, файлах и сети. Единственный
//! вход: команды. Единственный выход: состояние мира и события.
//!
//! Правила, которые нельзя нарушать (подробно в CLAUDE.md):
//! - никаких чисел с плавающей точкой в логике;
//! - никакого обхода HashMap/HashSet (порядок не определён);
//! - случайность только через генератор с сидом из состояния мира.

// Арифметика на float запрещена линтером: результат может отличаться
// между процессорами, а это ломает реплеи и будущую сетевую игру.
#![deny(clippy::float_arithmetic)]

pub mod fixed;

/// Версия правил симуляции. Увеличивается при любом изменении логики,
/// после которого старые реплеи перестают сходиться.
pub const SIM_VERSION: u32 = 1;

/// Сколько раз в секунду продвигается симуляция.
pub const TICKS_PER_SECOND: u32 = 30;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tick_rate_is_fixed() {
        assert_eq!(TICKS_PER_SECOND, 30);
    }
}
