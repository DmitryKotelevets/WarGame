#!/usr/bin/env bash
# Проверка, что в коде не осталось заглушек `todo!` и `unimplemented!`.
#
# Во время работы над шагом заглушки разрешены, поэтому в check.sh эта
# проверка не входит. В master их быть не должно: за этим следит CI.
#
# Запуск: scripts/check-todo.sh (из любой папки проекта).
# Код возврата: 0 если заглушек нет, 1 если есть, 2 если поиск сломался.

# -u: обращение к неопределённой переменной считается ошибкой.
# Флага -e здесь нет намеренно: grep возвращает 1, когда ничего не нашёл,
# а для нас это как раз хороший исход. Код возврата разбирается ниже.
set -u

# Переходим в корень репозитория, как в check.sh.
cd "$(dirname "$0")/.." || exit 2

# -r: во всех вложенных папках; -n: с номером строки;
# --include: только исходники Rust;
# -E: шаблон с «или». Восклицательный знак отличает макрос от слова
# «todo» в обычном тексте.
grep -rnE --include='*.rs' 'todo!|unimplemented!' crates
status=$?

if [ "$status" -eq 0 ]; then
    # grep что-то нашёл и уже напечатал строки выше.
    echo "== Найдены заглушки: в master их быть не должно"
    exit 1
fi

if [ "$status" -eq 1 ]; then
    echo "== Заглушек todo! и unimplemented! нет"
    exit 0
fi

echo "== Поиск завершился с ошибкой (код grep: $status)"
exit 2
