#!/usr/bin/env bash
# Проверка проекта одной командой: форматирование, clippy, тесты.
# Этот же скрипт запускает CI, поэтому локальный результат совпадает с CI.
#
# Запуск: scripts/check.sh (из любой папки проекта).

# -e: остановиться на первой упавшей команде;
# -u: обращение к неопределённой переменной считается ошибкой;
# pipefail: ошибка в середине цепочки `a | b` не теряется.
set -euo pipefail

# Переходим в корень репозитория (папка на уровень выше скрипта),
# чтобы cargo видел весь workspace независимо от того, откуда нас запустили.
cd "$(dirname "$0")/.."

# Порядок от быстрой проверки к долгой: опечатка в форматировании
# не должна ждать сборки и тестов.

echo "== 1/3 Форматирование (cargo fmt --check)"
cargo fmt --all --check

echo "== 2/3 Clippy (предупреждения запрещены)"
cargo clippy --all-targets -- -D warnings

echo "== 3/3 Тесты"
cargo test --workspace

echo "== Все проверки прошли"
